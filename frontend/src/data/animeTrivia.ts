/**
 * Manages shuffle-then-cycle rotation across anime trivia entries.
 * Avoids showing the same trivia line immediately across cycle transitions.
 */
export class TriviaCycleManager {
  public readonly items: readonly string[];
  public shuffledIndices: number[];
  public currentIndex: number;

  constructor(items: readonly string[] = ANIME_TRIVIA_ITEMS) {
    this.items = items;
    this.currentIndex = 0;
    this.shuffledIndices = this.shuffle(this.items.length);
  }

  /**
   * Generates a shuffled indices array using the Fisher-Yates algorithm.
   * If avoidFirstIndex is provided and matches the initial item, swaps it to prevent repeats.
   */
  private shuffle(length: number, avoidFirstIndex?: number): number[] {
    const indices: number[] = Array.from({ length }, (_, index) => index);
    if (length <= 1) {
      return indices;
    }

    for (let i = length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      const temp = indices[i];
      indices[i] = indices[j];
      indices[j] = temp;
    }

    if (avoidFirstIndex !== undefined && indices[0] === avoidFirstIndex && length > 1) {
      const swapTarget = 1 + Math.floor(Math.random() * (length - 1));
      const temp = indices[0];
      indices[0] = indices[swapTarget];
      indices[swapTarget] = temp;
    }

    return indices;
  }

  /**
   * Ensures indices are available, reshuffling if the current cycle was exhausted.
   */
  private ensureAvailable(): void {
    if (this.items.length === 0) {
      return;
    }

    if (this.currentIndex >= this.shuffledIndices.length) {
      const lastIndex =
        this.shuffledIndices.length > 0
          ? this.shuffledIndices[this.shuffledIndices.length - 1]
          : undefined;
      this.shuffledIndices = this.shuffle(this.items.length, lastIndex);
      this.currentIndex = 0;
    }
  }

  /**
   * Returns the next trivia item in sequence, reshuffling across cycle boundaries.
   */
  public getNextTrivia(): string {
    if (this.items.length === 0) {
      return '';
    }
    this.ensureAvailable();
    const itemIndex = this.shuffledIndices[this.currentIndex];
    this.currentIndex += 1;
    return this.items[itemIndex];
  }

  /**
   * Returns the upcoming trivia line without advancing the position pointer.
   */
  public peek(): string {
    if (this.items.length === 0) {
      return '';
    }
    this.ensureAvailable();
    const itemIndex = this.shuffledIndices[this.currentIndex];
    return this.items[itemIndex];
  }

  /**
   * Resets the manager from scratch with a fresh shuffle and resets pointer.
   */
  public reset(): void {
    this.shuffledIndices = this.shuffle(this.items.length);
    this.currentIndex = 0;
  }
}
